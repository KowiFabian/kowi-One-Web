import {test,expect} from '@playwright/test';
test('School Free: diagnosis, practice, feedback, persistence and export',async({page})=>{
 await page.goto('/school/aprender');
 await expect(page.getByRole('heading',{name:'De tu primera pregunta a un proyecto seguro.'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Ver demo ilustrativa',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Diagnóstico',exact:true}).click();
 await page.getByRole('button',{name:'Recomendar mi ruta'}).click();
 await expect(page.locator('main').getByRole('alert')).toContainText('Responde las tres');
 await page.getByLabel('Abro la fuente y compruebo que respalda la afirmación.').check();
 await page.getByLabel('Casos ficticios.',{exact:true}).check();
 await page.getByLabel('Propón tres tareas para 20 minutos, sin inventar información.').check();
 await page.getByRole('button',{name:'Recomendar mi ruta'}).click();
 await expect(page.getByRole('status')).toContainText('Puedes empezar por el proyecto');
 await page.getByRole('button',{name:'Aula y mapa',exact:true}).click();
 await page.getByRole('button',{name:'Evaluar y registrar'}).click();
 await expect(page.locator('main').getByRole('alert')).toContainText('Selecciona una respuesta');
 await page.getByLabel(/Guardar mis ejercicios/).check();
 await page.getByRole('textbox').fill('Caso ficticio: organizo una semana de estudio, verifico mis horarios y yo apruebo el plan.');
 for(const text of ['La tarea es reversible.','Identifico un dato que debo verificar.','Asigno la decisión final a una persona.'])await page.getByLabel(text,{exact:true}).check();
 await page.getByLabel('Solo que generó una respuesta convincente; debo comprobar el horario.').check();
 await page.getByRole('button',{name:'Evaluar y registrar'}).click();
 await expect(page.getByRole('status').filter({hasText:'Lección completada'})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('textbox')).toContainText('Caso ficticio');
 await page.getByRole('button',{name:'Progreso y portafolio',exact:true}).click();
 await expect(page.getByText('1 de 5 lecciones completadas.',{exact:false})).toBeVisible();
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Exportar evidencias JSON'}).click();
 expect((await download).suggestedFilename()).toBe('kowi-school-evidencias.json');
 await page.getByLabel(/Guardar mis ejercicios/).uncheck();
 await page.reload();
 await page.getByRole('button',{name:'Progreso y portafolio',exact:true}).click();
 await expect(page.getByText('0 de 5 lecciones completadas.',{exact:false})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1)).toBe(false);
});
test('School Free remains usable with browser storage blocked',async({page})=>{
 await page.addInitScript(()=>{Object.defineProperty(window,'localStorage',{get(){throw new Error('Blocked');}});});
 await page.goto('/school/aprender');
 await expect(page.locator('main').getByRole('alert')).toContainText('No podemos acceder');
 await expect(page.getByRole('button',{name:'Evaluar y registrar'})).toBeVisible();
});
